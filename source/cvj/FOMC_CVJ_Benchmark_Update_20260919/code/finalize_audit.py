"""Create a matched corpus audit and package-level numerical quality checks."""
from pathlib import Path
import hashlib,json,sys
import numpy as np
import pandas as pd
R=Path(__file__).resolve().parents[1]


def main():
    old=pd.read_csv(R/'results/uploaded_as_received/author_method_minutes_meeting_counts.csv')
    dic=pd.read_csv(R/'results/dictionary_only_correction/author_method_minutes_meeting_counts.csv')
    new=pd.read_csv(R/'results/audited_reconstruction/meeting_counts.csv')
    joined=new.copy()
    for label,df in [('uploaded',old),('dictionary_only',dic)]:
        df=df.set_index('meeting_date').reindex(new.meeting_date)
        for sign in ['negative','positive']:
            joined[label+'_'+sign]=df['author_method_'+sign+'_count'].to_numpy()
    joined['negative_change']=joined.negative_count-joined.uploaded_negative
    joined['positive_change']=joined.positive_count-joined.uploaded_positive
    joined.to_csv(R/'audit/meeting_level_count_changes.csv',index=False)
    totals=[]
    for period,mask in [('2000–2024',np.ones(len(joined),dtype=bool)),('2000–2016',joined.meeting_date<'2017-01-01'),('2017–2024',joined.meeting_date>='2017-01-01')]:
        s=joined.loc[mask]
        for version,neg,pos in [('Uploaded','uploaded_negative','uploaded_positive'),('Dictionary only','dictionary_only_negative','dictionary_only_positive'),('Audited','negative_count','positive_count')]:
            totals.append(dict(period=period,version=version,documents=len(s),negative=int(s[neg].sum()),positive=int(s[pos].sum()),classified=int(s[neg].sum()+s[pos].sum())))
    pd.DataFrame(totals).to_csv(R/'audit/count_totals_by_period.csv',index=False)
    # Quantify changed series without interpreting agreement as accuracy.
    audit={'documents':len(joined),'overlap_documents_2000_2016':int((joined.meeting_date<'2017-01-01').sum()),
           'meetings_changed_uploaded_to_audited':int(((joined.negative_change!=0)|(joined.positive_change!=0)).sum()),
           'negative_count_correlation':float(joined.negative_count.corr(joined.uploaded_negative)),
           'positive_count_correlation':float(joined.positive_count.corr(joined.uploaded_positive)),
           'original_author_series_available':False,
           'scope':'All available 2000–2024 minutes; no 1994–1999 minutes or original count outputs supplied.'}
    (R/'audit/count_comparison_summary.json').write_text(json.dumps(audit,indent=2))
    checks={}
    checks['uploaded_source_unchanged']=hashlib.sha256((R/'sources/replicate_author_method_counts.py').read_bytes()).hexdigest()=='a9d4f9093cdb25ccdb6cf6d62dadf708657e68fa5de9634591af106ee8520ac4'
    checks['200_unique_meetings']=len(joined)==200 and joined.meeting_date.is_unique
    checks['nonnegative_integer_counts']=bool(((joined[['negative_count','positive_count']]>=0)&(joined[['negative_count','positive_count']]%1==0)).all().all())
    h=pd.read_csv(R/'results/audited_reconstruction/all_phrase_audit.csv')
    checks['noun_audit_total']=len(h)==int(joined.noun_hits_total.sum())
    checks['classified_audit_total']=int(h.sign.isin(['negative','positive']).sum())==int(joined.classified_total.sum())
    t=pd.read_csv(R/'audit/synthetic_procedural_tests.csv');checks['all_24_code_cases_pass']=len(t)==24 and bool(t.audited_pass.all())
    p=pd.read_csv(R/'results/common_task_predictions.csv')
    checks['99_evaluations_per_pipeline']=bool(p.groupby('model').size().eq(99).all())
    checks['unique_predictions']=not p.duplicated(['model','date']).any()
    checks['strict_chronology']=bool((p.train_last<p.date).all())
    checks['finite_predictions']=bool(np.isfinite(p.prediction).all())
    perf=pd.read_csv(R/'results/common_task_performance.csv')
    headline=perf[(perf.period=='All evaluation')&(perf.model=='gemini_vector')].iloc[0]
    checks['headline_RMSE_unchanged']=bool(np.isclose(headline.rmse,3.5217640852469936,atol=1e-11))
    checks['headline_R2_unchanged']=bool(np.isclose(headline.oos_r2,.5011820659982482,atol=1e-11))
    (R/'audit/quality_checks.json').write_text(json.dumps(checks,indent=2))
    assert all(checks.values()),checks
    sources={str(p.relative_to(R)):{'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'bytes':p.stat().st_size} for p in (R/'sources').glob('*') if p.is_file()}
    (R/'audit/source_checksums.json').write_text(json.dumps(sources,indent=2))
    # Do not let inherited automatic reports silently assert known false claims.
    warning='This report was generated by the uploaded legacy reporting code. Its dictionary-table and hypothetical-exclusion assertions are not accepted findings. See audit/Implementation_Audit.md and the audited dictionary. The uploaded source and raw output have been retained for provenance.\n'
    for v in ['uploaded_as_received','dictionary_only_correction']:
        (R/'results'/v/'READ_BEFORE_USING_LEGACY_REPORT.txt').write_text(warning)
    print('All',len(checks),'integrity checks passed.')
    print(pd.DataFrame(totals).to_string(index=False))

if __name__=='__main__':main()
